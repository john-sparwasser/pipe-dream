internal static partial class LmLevelEntry
{
    public const int Bank = 0x1E;   // bank $1F is where LM keeps its own render engine (LmLevelRender)
    public const int BlockASnes = (Bank << 16) | 0x8141, BlockBSnes = (Bank << 16) | 0x8AD5;
    /// <summary>Bank bytes of the long operands: LDA ,X twice in A (the BG table),
    /// LDA ,X / LDA ,X in B (the height tables).</summary>
    private static readonly int[] BankBytesA = [0x035, 0x049], BankBytesB = [0x325, 0x333];

    public static byte[] BlockA() => Relocated(HexA, BankBytesA);
    public static byte[] BlockB() => Relocated(HexB, BankBytesB);

    private static byte[] Relocated(string hex, int[] bankBytes)
    {
        var b = Convert.FromHexString(hex);
        foreach (int at in bankBytes) b[at] = Bank;
        return b;
    }

    /// <summary>The fourteen hooks, as (site, LM's bytes) — the bank byte is rewritten on the
    /// way out. Two sites also NOP a trailing byte ($05DA17, $02950B).</summary>
    public static IEnumerable<(int Snes, byte[] Bytes)> Hooks()
    {
        foreach (var (site, hex) in new[]
        {
            (0x05DA17, "22418110EA"), (0x009708, "22C18310"), (0x00F871, "5C118410"), (0x00F77B, "5C318410"),
            (0x00F79D, "5C418410"), (0x05BCA5, "5C518510"), (0x00E966, "5C018610"), (0x05DA8A, "22158D10"),
            (0x05DB5F, "22158D10"), (0x0C9436, "22408D10"), (0x02950B, "5C5E8D10EA"), (0x0295BE, "5C728D10"),
            (0x00F70D, "5C848D10"), (0x05D9A1, "229C8D10"),
        })
        {
            var b = Convert.FromHexString(hex);
            b[3] = Bank;
            yield return (site, b);
        }
    }

