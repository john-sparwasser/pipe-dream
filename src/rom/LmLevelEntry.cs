/// <summary>
/// Lunar Magic's level-entry engine — the two code blocks a plain LM save installs for level
/// height, FG/BG initial position and "set FG/BG relative to player" — as the exact bytes
/// after.smc carries at $108141 (0x510) and $108AD5 (0x3C0). Fourteen hook sites in banks
/// 00/02/05/0C feed them (reference/LM_PARITY.md).
///
/// LM relocates these per ROM and the ONLY things that move are 16-bit in-bank operands (the
/// two jump tables, JSR/JMP) and the bank byte of four long operands — verified by diffing
/// after.smc against ShaoBase, whose copies sit at $139F01 and $10F4D1. So prep v10 keeps
/// LM's in-bank offsets and changes the bank: $1F:8141 and $1F:8AD5, with those four bytes
/// patched. Everything else is byte-for-byte LM's.
///
/// What the blocks hold (offsets from A / B):
///   A+000  the $05DA17 tail: layer-2 scroll setting, $1443-, then FG/BG initial
///          position — vanilla's fixed table, or relative to Mario's Y when $13CD bit 7 is set
///   A+1F3  jump table for the BG scroll-rate handlers, A+233 BG offset table (0x40)
///   A+280  $009708: level width from the header, $142A/$F9 for the relative camera
///   A+2D0  $00F871//: layer-2 scroll bounds during play
///   A+410  $05BCA5, A+4C0 $00E966: bounds against the level height
///   B+000  per-level height byte (0x200, all zero = vanilla), B+200 height LUT (index 0 = )
///   B+240  $05DA8A/: $13D7 = height, per-screen tilemap pointers $0BF6/$0C56
///   B+26B  $0C9436, B+289 $02950B, B+29D $0295BE, B+2AF $00F70D
///   B+2C7  the $05D9A1 vertical check, which also rebuilds the pointer tables
